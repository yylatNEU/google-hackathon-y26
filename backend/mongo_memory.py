    def role_quality_priors(self, scenario_key: str | None = None, limit: int = 200) -> dict[str, Any]:
        safe_limit = max(1, min(500, int(limit or 200)))
        rows = [
            row
            for row in self._collection_rows("agent_role_proposals", safe_limit)
            if not scenario_key or row.get("scenarioKey") == scenario_key
        ]
        by_agent: dict[str, list[dict[str, Any]]] = {}
        for row in rows:
            agent_id = str(row.get("agentId") or "")
            if agent_id:
                by_agent.setdefault(agent_id, []).append(row)

        priors = []
        for agent_id, agent_rows in sorted(by_agent.items()):
            sample_count = len(agent_rows)
            accepted = [row for row in agent_rows if bool(row.get("accepted")) or row.get("status") == "accepted"]
            rejected = [row for row in agent_rows if row.get("status") == "rejected"]
            positive = [
                row
                for row in accepted
                if (row.get("learningSignal", {}) if isinstance(row.get("learningSignal"), dict) else {}).get("status") == "positive_prior"
                or _number((row.get("outcomeMetrics", {}) if isinstance(row.get("outcomeMetrics"), dict) else {}).get("response_score")) >= 78
            ]
            needs_adjustment = [
                row
                for row in accepted
                if (row.get("learningSignal", {}) if isinstance(row.get("learningSignal"), dict) else {}).get("status") == "needs_adjustment"
            ]
            response_scores = [
                _number((row.get("outcomeMetrics", {}) if isinstance(row.get("outcomeMetrics"), dict) else {}).get("response_score"))
                for row in agent_rows
                if isinstance(row.get("outcomeMetrics"), dict)
            ]
            take_rates = [
                _number((row.get("outcomeMetrics", {}) if isinstance(row.get("outcomeMetrics"), dict) else {}).get("take_rate"))
                for row in agent_rows
                if isinstance(row.get("outcomeMetrics"), dict)
            ]
            accepted_rate = len(accepted) / sample_count if sample_count else 0
            rejected_rate = len(rejected) / sample_count if sample_count else 0
            positive_rate = len(positive) / len(accepted) if accepted else 0
            adjustment_rate = len(needs_adjustment) / len(accepted) if accepted else 0
            avg_response = round(sum(response_scores) / len(response_scores), 2) if response_scores else 0
            avg_take_rate = round(sum(take_rates) / len(take_rates), 3) if take_rates else 0
            prior_adjustment = round(
                _bounded_number(
                    accepted_rate * 4
                    + positive_rate * 4
                    - rejected_rate * 3
                    - adjustment_rate * 4
                    + ((avg_response - 78) / 8 if avg_response else 0),
                    -6,
                    6,
                )
            )
            priors.append(
                {
                    "agent_id": agent_id,
                    "sample_count": sample_count,
                    "accepted_count": len(accepted),
                    "rejected_count": len(rejected),
                    "positive_count": len(positive),
                    "needs_adjustment_count": len(needs_adjustment),
                    "accepted_rate": round(accepted_rate, 3),
                    "positive_rate": round(positive_rate, 3),
                    "avg_response_score": avg_response,
                    "avg_take_rate": avg_take_rate,
                    "prior_adjustment": int(prior_adjustment),
                    "confidence": "measured" if sample_count >= 3 else "directional",
                    "rationale": (
                        "Measured role proposal outcomes support a positive scoring prior."
                        if prior_adjustment > 0
                        else "Measured role proposal outcomes suggest caution for this role."
                        if prior_adjustment < 0
                        else "Measured role proposal outcomes are neutral so far."
                    ),
                }
            )
        return {
            "mode": "role_quality_priors",
            "scenario_key": scenario_key or "all",
            "sample_count": len(rows),
            "priors": priors,
            "by_agent": {item["agent_id"]: item for item in priors},
        }

