    def retrieve_context(
        self,
        query: str,
        state: dict[str, Any] | None = None,
        limit: int = 3,
        agent_role: str | None = None,
        cache_policy: str = "normal",
    ) -> dict[str, Any]:
        retrieval_started = time.monotonic()
        search_text = _query_text(query, state)
        current_state = state or self.latest_park_state()
        scenario_key = _scenario_key_from_state(current_state or state or {})
        if scenario_key == "unknown":
            scenario_key = _scenario_key_from_text(search_text, "unknown")
        role = _normalize_agent_role(agent_role, search_text)
        precomputed_cache = self._latest_agent_context_cache(scenario_key) if scenario_key != "unknown" else None
        bypass_role_cache = cache_policy in {"bypass_role_cache", "fresh_retrieval", "no_cache"}
        role_cache = None if bypass_role_cache else self._latest_role_context_cache(scenario_key, role) if scenario_key != "unknown" else None
        current_state_for_gate = current_state or state or {}
        current_state_fingerprint = _state_fingerprint(current_state_for_gate)
        current_semantic_summary = _state_semantic_summary(current_state_for_gate)
        freshness_gate = (
            {
                "allowed": False,
                "isFresh": False,
                "isUsable": False,
                "eventType": "role_cache_bypassed",
                "reason": "replay_or_policy_requested_fresh_retrieval",
                "trustLevel": "fresh_retrieval",
                "cacheTrustPenalty": 0.0,
                "mustRevalidate": False,
                "semanticDrift": {"level": "bypassed", "reasons": []},
                "agentInstruction": "Role cache bypassed; use fresh retrieval.",
            }
            if bypass_role_cache
            else self._role_cache_freshness_gate(role_cache, role, current_state_fingerprint, current_semantic_summary)
        )
        if freshness_gate["allowed"] and role_cache and isinstance(role_cache.get("retrieved"), dict):
            retrieved_payload = role_cache.get("retrieved", {})
            playbooks = retrieved_payload.get("playbooks", [])[:limit]
            incidents = retrieved_payload.get("incidents", [])[:limit]
            learnings = retrieved_payload.get("learnings", [])[:limit]
            playbook_method = "role_context_cache" if freshness_gate.get("trustLevel") == "fresh" else "role_context_cache_stale_usable"
            if freshness_gate.get("trustLevel") == "stale_usable":
                self._schedule_role_cache_refresh(scenario_key, role, search_text)
        else:
            playbooks, playbook_method = self._retrieve_playbooks(search_text, limit)
            incidents = self._retrieve_incidents(search_text, limit)
            learnings = self._retrieve_learnings(search_text, limit)
        self._record_cache_event(
            freshness_gate["eventType"],
            scenario_key,
            role,
            {
                "query": search_text[:220],
                "method": playbook_method,
                "hit": freshness_gate["allowed"],
                "limit": limit,
                "reason": freshness_gate["reason"],
                "cachePolicy": cache_policy,
                "trustLevel": freshness_gate.get("trustLevel"),
                "cacheTrustPenalty": freshness_gate.get("cacheTrustPenalty"),
                "mustRevalidate": freshness_gate.get("mustRevalidate"),
                "semanticDrift": freshness_gate.get("semanticDrift"),
                "freshUntil": freshness_gate.get("freshUntil"),
                "usableUntil": freshness_gate.get("usableUntil"),
                "refreshState": freshness_gate.get("refreshState"),
                "latencyMs": round((time.monotonic() - retrieval_started) * 1000, 2),
            },
        )
        self._refresh_agent_performance_scorecards(scenario_key, [role])
        self._record_working_memory(role, scenario_key, search_text, role_cache, playbook_method)
        return {
            "status": self.status(),
            "query": search_text,
            "current_state": current_state,
            "scenario_key": scenario_key,
            "agent_role": role,
            "cache_policy": cache_policy,
            "retrieved": {
                "playbooks": playbooks,
                "incidents": incidents,
                "learnings": learnings,
                "method": playbook_method,
            },
            "precomputed_context": precomputed_cache,
            "role_context": role_cache,
            "freshness_gate": freshness_gate,
            "cache_accuracy": {
                "trustLevel": freshness_gate.get("trustLevel"),
                "cacheTrustPenalty": freshness_gate.get("cacheTrustPenalty", 0),
                "mustRevalidate": bool(freshness_gate.get("mustRevalidate")),
                "semanticDrift": freshness_gate.get("semanticDrift", {"level": "unknown"}),
                "instruction": freshness_gate.get("agentInstruction", ""),
            },
            "cacheTrustPenalty": freshness_gate.get("cacheTrustPenalty", 0),
            "mustRevalidate": bool(freshness_gate.get("mustRevalidate")),
            "cache_layers": {
                "L0": "request_context",
                "L1": "fresh_role_context_cache",
                "L2": "stale_usable_role_context_cache",
                "L3": "scenario_memory_index",
                "L4": "mongodb_vector_or_text_retrieval",
                "L5": "bigquery_or_autodream_historical_priors",
                "selected": playbook_method,
            },
            "summary": (
                f"Retrieved {len(playbooks)} playbooks, {len(incidents)} past incidents, and {len(learnings)} learned outcome rules "
                f"for {role} from {playbook_method} over {self.mode} operational memory."
            ),
        }

    def _retrieve_playbooks(self, search_text: str, limit: int) -> tuple[list[dict[str, Any]], str]:
        collection = self._collection("playbooks")
        projection = {"embedding": 0, "embeddingText": 0}
        if collection is not None:
            try:
                rows = list(
                    collection.aggregate(
                        [
                            {
                                "$vectorSearch": {
                                    "index": self.vector_index,
                                    "path": "embedding",
                                    "queryVector": _vectorize(search_text),
                                    "numCandidates": 50,
                                    "limit": limit,
                                }
                            },
                            {"$project": {**projection, "score": {"$meta": "vectorSearchScore"}}},
                        ]
                    )
                )
                rows = [row for row in rows if not _is_rollback_watch_document(row)]
                return [_public_doc(row) for row in rows[:limit]], "mongodb_vector_search"
            except Exception as error:
                self.errors.append(f"Vector search fallback used: {error}")
                try:
                    rows = list(
                        collection.find(
                            {"$text": {"$search": search_text}},
                            {**projection, "score": {"$meta": "textScore"}},
                        )
                        .sort([("score", {"$meta": "textScore"})])
                        .limit(limit)
                    )
                    if rows:
                        rows = [row for row in rows if not _is_rollback_watch_document(row)]
                        return [_public_doc(row) for row in rows[:limit]], "mongodb_text_search"
                except Exception as text_error:
                    self.errors.append(f"Text search fallback used: {text_error}")

        rows = sorted(
            [deepcopy(row) for row in self._fallback["playbooks"] if not _is_rollback_watch_document(row)],
            key=lambda row: _keyword_score(row, search_text),
            reverse=True,
        )[:limit]
        return [_public_doc({**row, "score": _keyword_score(row, search_text)}) for row in rows], "keyword_similarity"

