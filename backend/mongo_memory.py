    def _role_cache_freshness_gate(
        self,
        role_cache: dict[str, Any] | None,
        agent_role: str,
        current_state_fingerprint: str | None = None,
        current_semantic_summary: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        role = _normalize_agent_role(agent_role)
        if not role_cache:
            return {
                "allowed": False,
                "isFresh": False,
                "eventType": "role_cache_miss",
                "reason": "missing_role_cache",
                "trustLevel": "blocked",
                "cacheTrustPenalty": 0.25,
                "mustRevalidate": True,
                "semanticDrift": {"level": "unknown", "reasons": ["missing_role_cache"]},
                "agentInstruction": "No role cache is available; use fresh retrieval and avoid claiming cached evidence.",
                "policy": AGENT_ROLE_CONFIGS[role].get("cacheTtlSeconds", 90),
            }
        now = datetime.now(UTC)
        fresh_until = _parse_utc(role_cache.get("freshUntil"))
        usable_until = _parse_utc(role_cache.get("usableUntil"))
        is_fresh = fresh_until is not None and fresh_until >= now
        is_usable = usable_until is not None and usable_until >= now
        state_changed = bool(
            current_state_fingerprint
            and role_cache.get("stateFingerprint")
            and role_cache.get("stateFingerprint") != current_state_fingerprint
        )
        drift = (
            _semantic_drift(role_cache.get("stateSemanticSummary"), current_semantic_summary, role)
            if state_changed
            else {
                "level": "none",
                "reasons": [],
                "allowStale": True,
                "cacheTrustPenalty": 0.0,
                "mustRevalidate": False,
            }
        )
        rollup = role_cache.get("rollup", {}) if isinstance(role_cache.get("rollup"), dict) else {}
        rollback_state = rollup.get("rollbackState") or (
            role_cache.get("scenarioMemory", {}) if isinstance(role_cache.get("scenarioMemory"), dict) else {}
        ).get("rollbackState")
        rollback_blocked = rollback_state == "rollback_watch" and role != "autodream_agent"
        if rollback_blocked:
            return {
                "allowed": False,
                "isFresh": is_fresh,
                "eventType": "role_cache_rollback_blocked",
                "reason": "rollback_watch_requires_fresh_retrieval",
                "trustLevel": "blocked",
                "cacheTrustPenalty": 0.4,
                "mustRevalidate": True,
                "semanticDrift": drift,
                "agentInstruction": "Rollback watch blocks cached live guidance; revalidate with fresh retrieval and operator review.",
                "freshUntil": role_cache.get("freshUntil"),
                "usableUntil": role_cache.get("usableUntil"),
                "rollbackState": rollback_state,
                "refreshState": role_cache.get("refreshState", "idle"),
            }
        if state_changed and not drift.get("allowStale", True):
            return {
                "allowed": False,
                "isFresh": is_fresh,
                "isUsable": is_usable,
                "eventType": "role_cache_dangerous_drift_blocked",
                "reason": "semantic_drift_dangerous",
                "trustLevel": "blocked",
                "cacheTrustPenalty": drift.get("cacheTrustPenalty", 0.35),
                "mustRevalidate": True,
                "semanticDrift": drift,
                "freshUntil": role_cache.get("freshUntil"),
                "usableUntil": role_cache.get("usableUntil"),
                "rollbackState": rollback_state or "active",
                "refreshState": role_cache.get("refreshState", "idle"),
                "agentInstruction": "Dangerous state drift detected; do not use cached guidance except as historical context.",
            }
        if is_fresh and not state_changed:
            return {
                "allowed": True,
                "isFresh": True,
                "isUsable": True,
                "eventType": "role_cache_read",
                "reason": "fresh_role_cache",
                "trustLevel": "fresh",
                "cacheTrustPenalty": 0.0,
                "mustRevalidate": False,
                "semanticDrift": drift,
                "agentInstruction": "Fresh role cache may be used as primary grounding.",
                "freshUntil": role_cache.get("freshUntil"),
                "usableUntil": role_cache.get("usableUntil"),
                "rollbackState": rollback_state or "active",
                "refreshState": role_cache.get("refreshState", "idle"),
            }
        if is_usable:
            material = drift.get("level") == "material"
            return {
                "allowed": True,
                "isFresh": False,
                "isUsable": True,
                "eventType": "role_cache_stale_usable",
                "reason": f"semantic_drift_{drift.get('level')}_stale_while_revalidate" if state_changed else "cache_ttl_expired_stale_while_revalidate",
                "trustLevel": "stale_usable",
                "cacheTrustPenalty": drift.get("cacheTrustPenalty", 0.12 if not material else 0.18) if state_changed else 0.12,
                "mustRevalidate": bool(drift.get("mustRevalidate", material)),
                "semanticDrift": drift,
                "agentInstruction": (
                    "Use stale cache only as provisional grounding; revalidate affected facts before final action."
                    if material
                    else "Use stale cache with a small confidence penalty while refresh runs."
                ),
                "freshUntil": role_cache.get("freshUntil"),
                "usableUntil": role_cache.get("usableUntil"),
                "rollbackState": rollback_state or "active",
                "refreshState": role_cache.get("refreshState", "idle"),
            }
        if not is_usable:
            return {
                "allowed": False,
                "isFresh": False,
                "isUsable": False,
                "eventType": "role_cache_stale",
                "reason": "cache_usable_window_expired",
                "trustLevel": "blocked",
                "cacheTrustPenalty": 0.3,
                "mustRevalidate": True,
                "semanticDrift": drift,
                "agentInstruction": "Cache is beyond usable window; rely on fresh retrieval.",
                "freshUntil": role_cache.get("freshUntil"),
                "usableUntil": role_cache.get("usableUntil"),
                "rollbackState": rollback_state,
                "refreshState": role_cache.get("refreshState", "idle"),
            }
        return {
            "allowed": True,
            "isFresh": True,
            "eventType": "role_cache_read",
            "reason": "fresh_role_cache",
            "trustLevel": "fresh",
            "cacheTrustPenalty": 0.0,
            "mustRevalidate": False,
            "semanticDrift": drift,
            "agentInstruction": "Fresh role cache may be used as primary grounding.",
            "freshUntil": role_cache.get("freshUntil"),
            "usableUntil": role_cache.get("usableUntil"),
            "rollbackState": rollback_state or "active",
            "refreshState": role_cache.get("refreshState", "idle"),
        }

    def _acquire_role_refresh_lease(self, scenario_key: str, agent_role: str, query: str) -> bool:
        role = _normalize_agent_role(agent_role)
        now = _utc_now()
        lease_until = _utc_after(30)
        cache_id = f"role_context_{scenario_key}_{role}"
        collection = self._collection("role_context_cache")
        update = {
            "refreshState": "refreshing",
            "refreshStartedAt": now,
            "refreshLeaseUntil": lease_until,
            "refreshReason": "stale_while_revalidate",
            "refreshQuery": query[:220],
        }
        if collection is not None:
            result = collection.update_one(
                {
                    "_id": cache_id,
                    "$or": [
                        {"refreshLeaseUntil": {"$exists": False}},
                        {"refreshLeaseUntil": {"$lte": now}},
                        {"refreshState": {"$ne": "refreshing"}},
                    ],
                },
                {"$set": _clean_for_bson(update)},
                upsert=False,
            )
            return bool(result.modified_count)
        for row in self._fallback["role_context_cache"]:
            if row.get("_id") != cache_id:
                continue
            lease = _parse_utc(row.get("refreshLeaseUntil"))
            if row.get("refreshState") == "refreshing" and lease and lease > datetime.now(UTC):
                return False
            row.update(_clean_for_bson(update))
            return True
        return False

    def _schedule_role_cache_refresh(self, scenario_key: str, agent_role: str, query: str) -> None:
        role = _normalize_agent_role(agent_role)
        if not self._acquire_role_refresh_lease(scenario_key, role, query):
            self._record_cache_event(
                "role_cache_refresh_suppressed",
                scenario_key,
                role,
                {"reason": "refresh_lease_already_held", "query": query[:220]},
            )
            return

        def refresh() -> None:
            try:
                self._refresh_operational_intelligence(scenario_key, query)
                self._record_cache_event(
                    "role_cache_refresh_complete",
                    scenario_key,
                    role,
                    {"source": "stale_while_revalidate"},
                )
            except Exception as error:
                self._mark_role_cache_refresh_failed(scenario_key, role, str(error)[:300])

        threading.Thread(target=refresh, name=f"parkpulse-cache-refresh-{scenario_key}-{role}", daemon=True).start()

    def _mark_role_cache_refresh_failed(self, scenario_key: str, agent_role: str, error: str) -> None:
        role = _normalize_agent_role(agent_role)
        now = _utc_now()
        cache_id = f"role_context_{scenario_key}_{role}"
        update = {
            "refreshState": "failed",
            "refreshFailedAt": now,
            "refreshError": error,
            "refreshLeaseUntil": now,
        }
        collection = self._collection("role_context_cache")
        if collection is not None:
            collection.update_one({"_id": cache_id}, {"$set": _clean_for_bson(update)}, upsert=False)
        else:
            for row in self._fallback["role_context_cache"]:
                if row.get("_id") == cache_id:
                    row.update(_clean_for_bson(update))
                    break
        self._record_cache_event("role_cache_refresh_failed", scenario_key, role, {"error": error})

    def _record_cache_event(
        self,
        event_type: str,
        scenario_key: str,
        agent_role: str | None,
        details: dict[str, Any] | None = None,
    ) -> None:
        now = _utc_now()
        role = _normalize_agent_role(agent_role, event_type)
        fingerprint = _stable_json(
            {
                "eventType": event_type,
                "scenarioKey": scenario_key,
                "agentRole": role,
                "createdAt": now,
                "details": details or {},
            }
        )
        document = {
            "_id": f"cache_event_{hashlib.sha1(fingerprint.encode('utf-8')).hexdigest()[:12]}",
            "documentType": "cache_event",
            "createdAt": now,
            "eventType": event_type,
            "scenarioKey": scenario_key,
            "agentRole": role,
            "details": details or {},
        }
        self._replace_memory_document("cache_events", document, 100)

