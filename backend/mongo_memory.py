def _public_doc(document: dict[str, Any] | None) -> dict[str, Any] | None:
    if document is None:
        return None
    public = {}
    for key, value in document.items():
        if key == "_id":
            public[key] = str(value)
        elif key not in {"embedding", "embeddingText"}:
            public[key] = _clean_for_bson(value)
    return public


_memory = OperationalMemory()
_memory_initialized = False
_memory_init_lock = threading.Lock()


def _initialize_memory_with_deadline() -> dict[str, Any]:
    return _memory.initialize()


def _ensure_memory_initialized() -> None:
    global _memory_initialized
    if _memory_initialized:
        return
    with _memory_init_lock:
        if _memory_initialized:
            return
        _initialize_memory_with_deadline()
        _memory_initialized = True


def _degrade_memory(error: BaseException) -> None:
    _memory.connected = False
    _memory.db = None
    _memory.client = None
    _memory.mode = "demo_fallback_degraded"
    _memory.errors.append(f"Operational memory degraded to fallback: {error}")
    _memory.seed_defaults()


def _safe_memory_call(name: str, operation, fallback, *, retry_operation_on_fallback: bool = True):
    try:
        if name != "mongo.initialize":
            _ensure_memory_initialized()
        return call_with_retries(name, operation, attempts=2, base_delay=0.05)
    except Exception as error:
        _degrade_memory(error)
        if not retry_operation_on_fallback:
            return fallback(error)
        try:
            return operation()
        except Exception as fallback_error:
            _memory.errors.append(f"Operational memory fallback failed: {fallback_error}")
            return fallback(fallback_error)


def init_operational_memory(force: bool = False) -> dict[str, Any]:
    global _memory_initialized
    if _memory_initialized and not force:
        return _memory.status()

    try:
        with _memory_init_lock:
            if _memory_initialized and not force:
                return _memory.status()
            status = call_with_retries("mongo.initialize", _initialize_memory_with_deadline, attempts=2, base_delay=0.05)
            _memory_initialized = True
            return status
    except Exception as error:
        _degrade_memory(error)
        _memory_initialized = True
        return _memory.status()


