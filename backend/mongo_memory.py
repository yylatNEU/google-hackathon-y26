        scenario = payload.get("scenario") if isinstance(payload.get("scenario"), dict) else {}
        generated_at = str(payload.get("generatedAt") or now)

        ticket_documents: list[dict[str, Any]] = []
        ticket_document_ids: list[str] = []
        source_ticket_ids: list[str] = []
        for ticket in tickets:
            source_ticket_id = str(ticket.get("id") or ticket.get("title") or _stable_json(ticket))
            source_ticket_ids.append(source_ticket_id)
            ticket_document_id = f"incident_ticket_{hashlib.sha1(source_ticket_id.encode('utf-8')).hexdigest()[:16]}"
            document = _clean_for_bson(
                {
                    **ticket,
                    "_id": ticket_document_id,
                    "documentType": "incident_ticket",
                    "ticketId": source_ticket_id,
                    "analyticsGeneratedAt": generated_at,
                    "createdAt": str(ticket.get("createdAt") or generated_at),
                    "updatedAt": now,
                    "scenarioKey": scenario.get("key") or scenario.get("id") or "active_park",
                    "scenarioName": scenario.get("name") or "Active park",
                    "reviewPosture": analytics_meta.get("reviewPosture") or "unknown",
                    "sourceMix": summary.get("sourceMix") or analytics_meta.get("bySource") or [],
                }
            )
            embedding_text = _document_text(document)
            document["embeddingText"] = embedding_text
            document["embedding"] = _vectorize(embedding_text)
            document["embeddingMetadata"] = _embedding_metadata()
            ticket_documents.append(document)
            ticket_document_ids.append(ticket_document_id)

        brief_digest = hashlib.sha1(
            _stable_json(
                {
                    "scenario": scenario.get("key") or scenario.get("id") or "active_park",
                    "headline": brief.get("headline"),
                    "humanDecision": brief.get("humanDecision"),
                    "recommendedCall": summary.get("recommendedCall"),
                    "ticketIds": source_ticket_ids,
                    "ticketStatuses": [
                        {
                            "id": ticket.get("id"),
                            "severity": ticket.get("severity"),
                            "status": ticket.get("status"),
                            "requiresHumanReview": ticket.get("requiresHumanReview"),
                        }
                        for ticket in tickets
                    ],
                }
            ).encode("utf-8")
        ).hexdigest()[:16]
        brief_document_id = f"operator_brief_{brief_digest}"
        brief_document = _clean_for_bson(
            {
                "_id": brief_document_id,
                "documentType": "operator_brief",
                "createdAt": generated_at,
                "updatedAt": now,
                "scenarioKey": scenario.get("key") or scenario.get("id") or "active_park",
                "scenarioName": scenario.get("name") or "Active park",
                "reviewPosture": analytics_meta.get("reviewPosture") or "unknown",
                "ticketIds": ticket_document_ids,
                "sourceTicketIds": source_ticket_ids,
                "summary": summary,
                "operatorBrief": brief,
                "humanReviewQueue": payload.get("humanReviewQueue") or [],
                "decisionSupport": payload.get("decisionSupport") or {},
                "memoryRole": "MongoDB stores the incident trail, evidence summary, and operator judgement brief for later review and eval.",
            }
        )
        brief_embedding_text = _document_text(brief_document)
        brief_document["embeddingText"] = brief_embedding_text
        brief_document["embedding"] = _vectorize(brief_embedding_text)
        brief_document["embeddingMetadata"] = _embedding_metadata()

        ticket_collection = self._collection("incident_tickets")
        brief_collection = self._collection("operator_briefs")
        if ticket_collection is not None and brief_collection is not None:
            if UpdateOne is not None and ticket_documents:
                ticket_collection.bulk_write(
                    [UpdateOne({"_id": document["_id"]}, {"$set": document}, upsert=True) for document in ticket_documents]
                )
            else:
                for document in ticket_documents:
                    ticket_collection.replace_one({"_id": document["_id"]}, document, upsert=True)
            brief_collection.replace_one({"_id": brief_document_id}, brief_document, upsert=True)
        else:
            existing_tickets = {row.get("_id"): row for row in self._fallback["incident_tickets"]}
            for document in ticket_documents:
                existing_tickets[document["_id"]] = document
            self._fallback["incident_tickets"] = sorted(
                existing_tickets.values(),
                key=lambda row: str(row.get("updatedAt") or row.get("createdAt") or ""),
                reverse=True,
            )[:240]

            self._fallback["operator_briefs"] = [
                row for row in self._fallback["operator_briefs"] if row.get("_id") != brief_document_id
            ]
            self._fallback["operator_briefs"].insert(0, brief_document)
            self._fallback["operator_briefs"] = self._fallback["operator_briefs"][:80]

        return {
            "status": "stored",
            "mode": self.mode,
            "connected": self.connected,
            "collections": ["incident_tickets", "operator_briefs"],
            "ticketCount": len(ticket_documents),
            "ticketIds": ticket_document_ids,
            "sourceTicketIds": source_ticket_ids,
            "operatorBriefId": brief_document_id,
            "dedupe": "tickets_upserted_by_stable_id_briefs_upserted_by_digest",
            "readinessIssues": list(self.errors[-3:]),
        }

