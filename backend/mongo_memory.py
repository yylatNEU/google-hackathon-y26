    def _ground_truth_contract_for_learning(self, dream_learning_id: str) -> dict[str, Any]:
        measurements = self._promotion_measurements_for_learning(dream_learning_id)
        if not measurements:
            return {
                "status": "not_measured",
                "measured_promotions": 0,
                "ground_truth_lift": 0.0,
                "regression_risk": False,
                "counts": {"improved": 0, "neutral": 0, "regressed": 0},
            }
        counts = {
            "improved": sum(1 for item in measurements if item.get("status") == "improved"),
            "neutral": sum(1 for item in measurements if item.get("status") == "neutral"),
            "regressed": sum(1 for item in measurements if item.get("status") == "regressed"),
        }
        take_lifts = [
            _number((item.get("lift", {}) if isinstance(item.get("lift"), dict) else {}).get("takeRate"))
            for item in measurements
        ]
        ground_truth_lift = round(sum(take_lifts) / len(take_lifts), 3) if take_lifts else 0.0
        regressed_rate = counts["regressed"] / len(measurements)
        return {
            "status": "measured",
            "measured_promotions": len(measurements),
            "ground_truth_lift": ground_truth_lift,
            "regression_risk": regressed_rate >= 0.25 or ground_truth_lift < 0,
            "counts": counts,
            "latest_measurement": measurements[0],
        }

    def autodream_promotion_readiness(
        self,
        dream_learning_id: str,
        cache_replay_audit: dict[str, Any] | None = None,
        benchmark: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        dream_learning = self._dream_learning_by_id(dream_learning_id)
        if not dream_learning:
            return {
                "status": "not_found",
                "dream_learning_id": dream_learning_id,
                "promotion_ready": False,
                "blockers": ["dream_learning_not_found"],
            }
        scenario_key = str(dream_learning.get("scenarioKey") or "unknown")
        cache_replay_audit = cache_replay_audit if isinstance(cache_replay_audit, dict) else None
        cache_passed = cache_replay_audit.get("status") == "passed" if cache_replay_audit else False
        if not cache_replay_audit:
            required_roles = {"react_agent", "proact_agent", "autodream_agent"}
            role_metrics = {role: self._cache_replay_metrics(role, scenario_key, 50) for role in required_roles}
            cache_passed = all(metrics.get("latestStatus") == "passed" and not metrics.get("failures") for metrics in role_metrics.values())
            cache_replay_audit = {
                "status": "passed" if cache_passed else "not_ready",
                "summary": {
                    "roles_checked": len(required_roles),
                    "roles_passed": sum(1 for metrics in role_metrics.values() if metrics.get("latestStatus") == "passed" and not metrics.get("failures")),
                    "failures": [
                        f"{role}:{failure}"
                        for role, metrics in role_metrics.items()
                        for failure in (metrics.get("failures") or ["not_run"] if metrics.get("latestStatus") != "passed" else [])
                    ],
                },
            }

        latest_benchmark = benchmark if isinstance(benchmark, dict) and benchmark.get("status") else self._latest_benchmark_for_dream_learning(dream_learning_id)
        benchmark_summary = latest_benchmark.get("summary", {}) if isinstance((latest_benchmark or {}).get("summary"), dict) else {}
        benchmark_confidence = (latest_benchmark or {}).get("confidence", "no_signal")
        paired_benchmark_passed = (
            (latest_benchmark or {}).get("status") == "complete"
            and benchmark_confidence in {"validated", "directional"}
            and _number(benchmark_summary.get("take_rate_lift")) >= 0
            and _number(benchmark_summary.get("win_rate")) >= 0.45
        )
        ground_truth = self._ground_truth_contract_for_learning(dream_learning_id)
        rollback_watch = self._rollback_watch_for_learning(dream_learning_id)
        regression_risk = bool(ground_truth.get("regression_risk")) or benchmark_confidence == "regression_risk" or bool(rollback_watch)
        blockers = []
        if not cache_passed:
            blockers.append("cache_replay_not_passed")
        if not paired_benchmark_passed:
            blockers.append("paired_benchmark_not_passed")
        if regression_risk:
            blockers.append("regression_risk")
        if rollback_watch:
            blockers.append("rollback_watch")
        promotion_ready = not blockers
        contract = {
            "status": "ready" if promotion_ready else "not_ready",
            "dream_learning_id": dream_learning_id,
            "scenario_key": scenario_key,
            "promotion_ready": promotion_ready,
            "cache_replay_passed": cache_passed,
            "paired_benchmark_passed": paired_benchmark_passed,
            "ground_truth_lift": _number(ground_truth.get("ground_truth_lift")),
            "live_ground_truth_status": ground_truth.get("status"),
            "regression_risk": regression_risk,
            "required_operator_review": True,
            "blockers": blockers,
            "cache_replay": {
                "status": cache_replay_audit.get("status"),
                "summary": cache_replay_audit.get("summary", {}),
            },
            "paired_benchmark": {
                "status": (latest_benchmark or {}).get("status", "not_run"),
                "confidence": benchmark_confidence,
                "sample_size": (latest_benchmark or {}).get("sample_size"),
                "summary": benchmark_summary,
                "benchmark_id": (latest_benchmark or {}).get("_id"),
            },
            "ground_truth": ground_truth,
            "rollback_watch": {
                "active": bool(rollback_watch),
                "documents": rollback_watch,
            },
        }
        return _public_doc(contract)

