def _ensure_mongo_driver() -> bool:
    global ASCENDING, DESCENDING, TEXT, MongoClient, UpdateOne, Collection, _MONGO_DRIVER_IMPORT_ATTEMPTED
    if MongoClient is not None:
        return True
    if _MONGO_DRIVER_IMPORT_ATTEMPTED:
        return False
    _MONGO_DRIVER_IMPORT_ATTEMPTED = True
    if str(os.getenv("MONGODB_DISABLE_DRIVER_IMPORT", "")).strip().lower() in {"1", "true", "yes"}:
        return False
    try:
        from pymongo import ASCENDING as pymongo_ascending
        from pymongo import DESCENDING as pymongo_descending
        from pymongo import TEXT as pymongo_text
        from pymongo import MongoClient as PymongoClient
        from pymongo import UpdateOne as PymongoUpdateOne
        from pymongo.collection import Collection as PymongoCollection
        import certifi
    except Exception:  # pragma: no cover - exercised when pymongo is not installed
        return False
    os.environ.setdefault("MONGODB_TLS_CA_FILE", certifi.where())
    ASCENDING = pymongo_ascending
    DESCENDING = pymongo_descending
    TEXT = pymongo_text
    MongoClient = PymongoClient
    UpdateOne = PymongoUpdateOne
    Collection = PymongoCollection
    return True


