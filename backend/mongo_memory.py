    def _scenario_documents(self, collection_name: str, scenario_key: str, limit: int = 5) -> list[dict[str, Any]]:
        projection = {"embedding": 0, "embeddingText": 0}
        field_by_collection = {
            "agent_learnings": "scenarioKey",
            "dream_learnings": "scenarioKey",
            "autodream_benchmarks": "scenarioKey",
            "playbooks": "incidentType",
            "incidents": "incidentType",
            "scenario_memory_index": "scenarioKey",
            "ops_metrics_rollups": "scenarioKey",
            "agent_context_cache": "scenarioKey",
            "role_context_cache": "scenarioKey",
            "agent_working_memory": "scenarioKey",
            "cache_events": "scenarioKey",
            "cache_accuracy_replays": "scenarioKey",
        }
        collection = self._collection(collection_name)
        field = field_by_collection.get(collection_name, "scenarioKey")
        if collection is not None:
            rows = list(
                collection.find({field: scenario_key}, projection)
                .sort([("updatedAt", DESCENDING), ("createdAt", DESCENDING)])
                .limit(max(1, limit))
            )
            return [_public_doc(row) for row in rows]

        def matches(row: dict[str, Any]) -> bool:
            if collection_name == "outcome_events":
                scenario = row.get("stateScenario", {}) if isinstance(row.get("stateScenario"), dict) else {}
                return scenario.get("key") == scenario_key
            return row.get(field) == scenario_key

        rows = sorted(
            [deepcopy(row) for row in self._fallback.get(collection_name, []) if matches(row)],
            key=lambda row: (row.get("updatedAt", ""), row.get("createdAt", "")),
            reverse=True,
        )[: max(1, limit)]
        return [_public_doc(row) for row in rows]

