    def ground_truth_improvement(self, limit: int = 100) -> dict[str, Any]:
        safe_limit = max(1, min(500, int(limit or 100)))
        minimum_sample_size = 5
        collection = self._collection("outcome_events")
        if collection is not None:
            rows = list(
                collection.find(
                    {"promotionImpactMeasurements.0": {"$exists": True}},
                    {"embedding": 0, "embeddingText": 0},
                )
                .sort("createdAt", DESCENDING)
                .limit(safe_limit)
            )
        else:
            rows = [
                deepcopy(row)
                for row in self._fallback["outcome_events"]
                if isinstance(row.get("promotionImpactMeasurements"), list) and row.get("promotionImpactMeasurements")
            ][:safe_limit]

        measurements: list[dict[str, Any]] = []
        for row in rows:
            for item in row.get("promotionImpactMeasurements", []) if isinstance(row.get("promotionImpactMeasurements"), list) else []:
                if isinstance(item, dict):
                    measurements.append({**item, "outcomeCreatedAt": row.get("createdAt")})

        if not measurements:
            return {
                "status": "not_measured",
                "source": "outcome_events.promotionImpactMeasurements",
                "confidence": "no_signal",
                "minimum_sample_size": minimum_sample_size,
                "recommendation": "No promoted AutoDream rule has enough measured outcomes yet.",
                "measured_outcomes": 0,
                "measured_promotions": 0,
                "counts": {"improved": 0, "neutral": 0, "regressed": 0},
                "averages": {},
                "totals": {},
                "scenario_breakdown": [],
                "latest_measurement": None,
            }

        def path_value(measurement: dict[str, Any], path: tuple[str, ...]) -> float:
            value: Any = measurement
            for key in path:
                value = value.get(key) if isinstance(value, dict) else None
            return _number(value)

        def avg(items: list[dict[str, Any]], path: tuple[str, ...]) -> float:
            values = []
            for measurement in items:
                value: Any = measurement
                for key in path:
                    value = value.get(key) if isinstance(value, dict) else None
                values.append(_number(value))
            return round(sum(values) / len(values), 3) if values else 0.0

        def counts_for(items: list[dict[str, Any]]) -> dict[str, int]:
            return {
                "improved": sum(1 for item in items if item.get("status") == "improved"),
                "neutral": sum(1 for item in items if item.get("status") == "neutral"),
                "regressed": sum(1 for item in items if item.get("status") == "regressed"),
            }

        def confidence_for(items: list[dict[str, Any]]) -> str:
            if not items:
                return "no_signal"
            item_counts = counts_for(items)
            improved_rate = item_counts["improved"] / len(items)
            regressed_rate = item_counts["regressed"] / len(items)
            take_lift = avg(items, ("lift", "takeRate"))
            if regressed_rate >= 0.25 or take_lift < 0:
                return "regression_risk"
            if len(items) < 3:
                return "early_signal"
            if len(items) < minimum_sample_size:
                return "directional"
            if improved_rate >= 0.7 and take_lift >= 0.05:
                return "validated"
            return "mixed"

        def recommendation_for(confidence: str, sample_size: int) -> str:
            if confidence == "validated":
                return "Validated for matching scenarios; keep using the promoted rule and keep measuring drift."
            if confidence == "regression_risk":
                return "Regression risk detected; review or roll back the promoted rule before broader use."
            if confidence == "mixed":
                return "Mixed results; keep the rule review-gated and inspect scenario-level variance."
            if confidence == "directional":
                return f"Directional signal only; collect {max(0, minimum_sample_size - sample_size)} more measured outcomes before generalizing."
            if confidence == "early_signal":
                return f"Early signal from {sample_size} measured outcome{'s' if sample_size != 1 else ''}; do not generalize yet."
            return "No measurement signal yet."

        counts = {
            "improved": sum(1 for item in measurements if item.get("status") == "improved"),
            "neutral": sum(1 for item in measurements if item.get("status") == "neutral"),
            "regressed": sum(1 for item in measurements if item.get("status") == "regressed"),
        }
        queued_values = [_number((item.get("lift", {}) if isinstance(item.get("lift"), dict) else {}).get("queuedGuestsAvoided")) for item in measurements]
        latest = measurements[0]
        scenario_groups: dict[str, list[dict[str, Any]]] = {}
        for measurement in measurements:
            scenario_key = str(measurement.get("scenarioKey") or "unknown")
            scenario_groups.setdefault(scenario_key, []).append(measurement)
        scenario_breakdown = []
        for scenario_key, items in sorted(scenario_groups.items()):
            item_counts = counts_for(items)
            scenario_confidence = confidence_for(items)
            scenario_breakdown.append(
                {
                    "scenario_key": scenario_key,
                    "measured_promotions": len(items),
                    "counts": item_counts,
                    "improved_rate": round(item_counts["improved"] / len(items), 3) if items else 0,
                    "confidence": scenario_confidence,
                    "averages": {
                        "baseline_take_rate": avg(items, ("baseline", "takeRate")),
                        "observed_take_rate": avg(items, ("observed", "takeRate")),
                        "take_rate_lift": avg(items, ("lift", "takeRate")),
                        "follow_through_lift": avg(items, ("lift", "followThroughRate")),
                        "overall_outcome_score": avg(items, ("observed", "overallOutcomeScore")),
                    },
                    "totals": {
                        "queued_guests_avoided": round(
                            sum(path_value(item, ("lift", "queuedGuestsAvoided")) for item in items),
                            1,
                        ),
                    },
                    "recommendation": recommendation_for(scenario_confidence, len(items)),
                }
            )
        confidence = confidence_for(measurements)
        return {
            "status": "measured",
            "source": "outcome_events.promotionImpactMeasurements",
            "confidence": confidence,
            "minimum_sample_size": minimum_sample_size,
            "recommendation": recommendation_for(confidence, len(measurements)),
            "measured_outcomes": len({item.get("sourceOutcomeId") for item in measurements if item.get("sourceOutcomeId")}),
            "measured_promotions": len(measurements),
            "counts": counts,
            "averages": {
                "baseline_take_rate": avg(measurements, ("baseline", "takeRate")),
                "observed_take_rate": avg(measurements, ("observed", "takeRate")),
                "take_rate_lift": avg(measurements, ("lift", "takeRate")),
                "baseline_follow_through_rate": avg(measurements, ("baseline", "followThroughRate")),
                "observed_follow_through_rate": avg(measurements, ("observed", "followThroughRate")),
                "follow_through_lift": avg(measurements, ("lift", "followThroughRate")),
                "overall_outcome_score": avg(measurements, ("observed", "overallOutcomeScore")),
            },
            "totals": {
                "queued_guests_avoided": round(sum(queued_values), 1),
            },
            "scenario_breakdown": scenario_breakdown,
            "latest_measurement": _public_doc(latest),
        }

