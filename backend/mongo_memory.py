    def review_dream_learning(
        self,
        dream_learning_id: str,
        review_status: str = "rejected",
        reviewer: str = "operator",
        reason: str = "",
    ) -> dict[str, Any]:
        self._invalidate_dashboard_cache()
        allowed_statuses = {"rejected", "archived", "needs_more_evidence"}
        safe_status = review_status if review_status in allowed_statuses else "rejected"
        now = _utc_now()
        collection = self._collection("dream_learnings")
        dream_learning = None
        if collection is not None:
            dream_learning = collection.find_one({"_id": dream_learning_id})
        else:
            dream_learning = next((row for row in self._fallback["dream_learnings"] if row.get("_id") == dream_learning_id), None)
        if not dream_learning:
            return {"status": "not_found", "dream_learning_id": dream_learning_id, "review_status": safe_status}
        if dream_learning.get("reviewStatus") == "promoted" or dream_learning.get("promoted"):
            return {
                "status": "already_promoted",
                "dream_learning_id": dream_learning_id,
                "review_status": dream_learning.get("reviewStatus"),
                "promoted_document_id": dream_learning.get("promotedDocumentId"),
            }

        review = {
            "reviewer": reviewer,
            "reviewedAt": now,
            "source": "autodream",
            "decision": safe_status,
            "reason": reason,
        }
        update = {
            "reviewStatus": safe_status,
            "promoted": False,
            "reviewer": reviewer,
            "reviewedAt": now,
            "reviewReason": reason,
            "promotionReview": review,
        }
        if collection is not None:
            collection.update_one({"_id": dream_learning_id}, {"$set": _clean_for_bson(update)}, upsert=False)
        else:
            for row in self._fallback["dream_learnings"]:
                if row.get("_id") == dream_learning_id:
                    row.update(_clean_for_bson(update))
                    break

        scenario_key = str(dream_learning.get("scenarioKey") or "unknown")
        if scenario_key != "unknown":
            self._refresh_operational_intelligence(scenario_key)
        return {
            "status": safe_status,
            "dream_learning_id": dream_learning_id,
            "reviewer": reviewer,
            "reason": reason,
        }


