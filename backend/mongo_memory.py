def _keyword_score(document: dict[str, Any], query: str) -> float:
    query_terms = {term for term in query.lower().replace("_", " ").split() if len(term) > 2}
    if not query_terms:
        return 0.0
    text = _document_text(document).lower().replace("_", " ")
    matches = sum(1 for term in query_terms if term in text)
    return round(matches / len(query_terms), 3)


def _truthy(value: str | None) -> bool:
    return str(value or "").strip().lower() in {"1", "true", "yes", "y", "on"}


