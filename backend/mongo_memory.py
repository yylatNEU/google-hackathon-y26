    def record_executive_experience_documents(self, collection_name: str, documents: list[dict[str, Any]]) -> dict[str, Any]:
        self._invalidate_dashboard_cache()
        if collection_name not in EXECUTIVE_EXPERIENCE_COLLECTIONS:
            return {
                "status": "blocked",
                "mode": self.mode,
                "collection": collection_name,
                "storedCount": 0,
                "documentIds": [],
                "reason": "Collection is not approved for Executive Experience Intelligence writes.",
            }
        from executive_experience_evidence import validate_executive_experience_documents

        validation = validate_executive_experience_documents(collection_name, documents)
        if not validation.get("valid"):
            return {
                "status": "blocked",
                "mode": self.mode,
                "collection": collection_name,
                "storedCount": 0,
                "documentIds": [],
                "validation": validation,
                "reason": "Executive evidence failed schema or privacy validation.",
            }
        now = _utc_now()
        cleaned_documents: list[dict[str, Any]] = []
        for index, document in enumerate(documents):
            if not isinstance(document, dict):
                continue
            source_id = str(document.get("_id") or document.get("id") or f"{collection_name}_{index}")
            document_id = source_id if source_id.startswith("exec_") else f"exec_{hashlib.sha1(f'{collection_name}:{source_id}'.encode('utf-8')).hexdigest()[:16]}"
            cleaned_documents.append(
                _clean_for_bson(
                    {
                        **document,
                        "_id": document_id,
                        "id": document_id,
                        "documentType": collection_name,
                        "createdAt": document.get("createdAt") or now,
                        "updatedAt": now,
                    }
                )
            )

        collection = self._collection(collection_name)
        if collection is not None:
            if UpdateOne is not None and cleaned_documents:
                collection.bulk_write([UpdateOne({"_id": document["_id"]}, {"$set": document}, upsert=True) for document in cleaned_documents])
            else:
                for document in cleaned_documents:
                    collection.replace_one({"_id": document["_id"]}, document, upsert=True)
        else:
            existing = {row.get("_id"): row for row in self._fallback.setdefault(collection_name, [])}
            for document in cleaned_documents:
                existing[document["_id"]] = document
            self._fallback[collection_name] = sorted(
                existing.values(),
                key=lambda row: str(row.get("updatedAt") or row.get("createdAt") or ""),
                reverse=True,
            )[:250]

        return {
            "status": "stored",
            "mode": self.mode,
            "connected": self.connected,
            "collection": collection_name,
            "storedCount": len(cleaned_documents),
            "documentIds": [str(document["_id"]) for document in cleaned_documents],
            "readinessIssues": list(self.errors[-3:]),
        }

    def backfill_embeddings(self, collection_names: list[str] | None = None, limit: int = 250) -> dict[str, Any]:
        self._invalidate_dashboard_cache()
        allowed = {"playbooks", "incidents", "agent_learnings"}
        selected = [name for name in (collection_names or sorted(allowed)) if name in allowed]
        safe_limit = max(1, min(1000, int(limit or 250)))
        now = _utc_now()
        results: dict[str, Any] = {}

        for name in selected:
            updated = 0
            skipped = 0
            errors: list[str] = []
            collection = self._collection(name)
            if collection is not None:
                try:
                    rows = list(collection.find({}, {}).limit(safe_limit))
                    for row in rows:
                        text = _document_text(row)
                        if not text.strip():
                            skipped += 1
                            continue
                        document_update = {
                            "embeddingText": text,
                            "embedding": _vectorize(text),
                            "embeddingMetadata": _embedding_metadata(),
                            "embeddingUpdatedAt": now,
                        }
                        collection.update_one({"_id": row.get("_id")}, {"$set": document_update}, upsert=False)
                        updated += 1
                except Exception as error:
                    errors.append(str(error)[:300])
            else:
                rows = self._fallback.get(name, [])[:safe_limit]
                for row in rows:
                    text = _document_text(row)
                    if not text.strip():
                        skipped += 1
                        continue
                    row["embeddingText"] = text
                    row["embedding"] = _vectorize(text)
                    row["embeddingMetadata"] = _embedding_metadata()
                    row["embeddingUpdatedAt"] = now
                    updated += 1

            results[name] = {
                "updated": updated,
                "skipped": skipped,
                "errors": errors,
            }

        return {
            "status": "repaired" if not any(item["errors"] for item in results.values()) else "partial_error",
            "mode": self.mode,
            "updatedAt": now,
            "collections": results,
        }

    def record_dream_run(self, dream_run: dict[str, Any], dream_learnings: list[dict[str, Any]]) -> dict[str, Any]:
        self._invalidate_dashboard_cache()
        now = _utc_now()
        run_id = str(dream_run.get("_id") or dream_run.get("dreamRunId") or f"dream_run_{hashlib.sha1(_stable_json(dream_run).encode('utf-8')).hexdigest()[:12]}")
        run_document = _clean_for_bson(
            {
                "_id": run_id,
                "documentType": "dream_run",
                "createdAt": dream_run.get("createdAt", now),
                "updatedAt": now,
                "status": "review_required",
                "offlineOnly": True,
                "promoted": False,
                **dream_run,
                "_id": run_id,
            }
        )
        learning_documents = []
        for index, learning in enumerate(dream_learnings):
            fingerprint = _stable_json(
                {
                    "runId": run_id,
                    "scenarioKey": learning.get("scenarioKey", "unknown"),
                    "lesson": learning.get("lesson", ""),
                    "rule": learning.get("rule", ""),
                    "index": index,
                }
            )
            document_id = str(learning.get("_id") or f"dream_learning_{hashlib.sha1(fingerprint.encode('utf-8')).hexdigest()[:12]}")
            document = _clean_for_bson(
                {
                    "_id": document_id,
                    "documentType": "dream_learning",
                    "createdAt": now,
                    "updatedAt": now,
                    "dreamRunId": run_id,
                    "offlineOnly": True,
                    "reviewStatus": "pending_operator_review",
                    "promoted": False,
                    **learning,
                    "_id": document_id,
                }
            )
            embedding_text = _document_text(document)
            document["embeddingText"] = embedding_text
            document["embedding"] = _vectorize(embedding_text)
            document["embeddingMetadata"] = _embedding_metadata()
            learning_documents.append(document)

        run_collection = self._collection("dream_runs")
        learning_collection = self._collection("dream_learnings")
        if run_collection is not None and learning_collection is not None:
            run_collection.replace_one({"_id": run_id}, run_document, upsert=True)
            for document in learning_documents:
                learning_collection.replace_one({"_id": document["_id"]}, document, upsert=True)
        else:
            self._fallback["dream_runs"] = [row for row in self._fallback["dream_runs"] if row.get("_id") != run_id]
            self._fallback["dream_runs"].insert(0, run_document)
            self._fallback["dream_runs"] = self._fallback["dream_runs"][:25]
            existing_ids = {row["_id"] for row in learning_documents}
            self._fallback["dream_learnings"] = [
                row for row in self._fallback["dream_learnings"] if row.get("_id") not in existing_ids
            ]
            self._fallback["dream_learnings"] = learning_documents + self._fallback["dream_learnings"]
            self._fallback["dream_learnings"] = self._fallback["dream_learnings"][:100]

        for scenario_key in sorted({str(document.get("scenarioKey", "unknown")) for document in learning_documents}):
            if scenario_key != "unknown":
                self._refresh_operational_intelligence(scenario_key)

        return {
            "status": "stored",
            "mode": self.mode,
            "dream_run_id": run_id,
            "dream_learning_ids": [document["_id"] for document in learning_documents],
        }

