    def _role_context_document(
        self,
        role: str,
        scenario_key: str,
        search_text: str,
        scenario_document: dict[str, Any],
        rollup_document: dict[str, Any],
        base_playbooks: list[dict[str, Any]],
        base_incidents: list[dict[str, Any]],
        base_learnings: list[dict[str, Any]],
        dream_learnings: list[dict[str, Any]],
        latest_benchmark: dict[str, Any] | None,
        now: str,
        retrieval_method: str,
    ) -> dict[str, Any]:
        role = _normalize_agent_role(role)
        config = AGENT_ROLE_CONFIGS[role]
        ttl_seconds = int(config.get("cacheTtlSeconds", 90) or 90)
        usable_stale_seconds = int(config.get("usableStaleSeconds", ttl_seconds * 3) or ttl_seconds * 3)
        state_snapshot = self.latest_park_state() or {}
        state_fingerprint = _state_fingerprint(state_snapshot)
        state_semantic_summary = _state_semantic_summary(state_snapshot)
        role_search_text = f"{search_text} {config['queryTerms']} {scenario_key}"
        role_playbooks, role_method = self._retrieve_playbooks(role_search_text, 4)
        role_incidents = self._retrieve_incidents(role_search_text, 4)
        role_learnings = self._retrieve_learnings(role_search_text, 6)
        playbooks = (role_playbooks or base_playbooks)[:4]
        incidents = (role_incidents or base_incidents)[:4]
        learnings = (role_learnings or base_learnings)[:6]
        if role == "autodream_agent":
            learnings = (dream_learnings + learnings)[:6]
        candidate_rules = dream_learnings[:5] if role == "autodream_agent" else scenario_document.get("activeRules", [])[:5]
        if role == "maintenance_agent":
            ride_rows = self.latest_documents("rides", 6)
            staff_rows = self.latest_documents("staff_shifts", 3)
            role_specific = {"rides": ride_rows, "staff": staff_rows}
        elif role == "scan_agent":
            role_specific = {"rawSignals": self.latest_documents("raw_signals", 6)}
        elif role == "proact_agent":
            role_specific = {"eventPlans": self.latest_documents("event_plans", 4)}
        elif role == "autodream_agent":
            role_specific = {
                "dreamQueue": dream_learnings[:5],
                "latestBenchmark": latest_benchmark,
            }
        else:
            role_specific = {
                "latestBenchmark": latest_benchmark,
                "candidateRules": candidate_rules,
        }
        return {
            "_id": f"role_context_{scenario_key}_{role}",
            "documentType": "role_context_cache",
            "createdAt": now,
            "updatedAt": now,
            "freshUntil": _utc_after(ttl_seconds),
            "usableUntil": _utc_after(ttl_seconds + usable_stale_seconds),
            "trustLevel": "fresh",
            "refreshState": "idle",
            "refreshLeaseUntil": None,
            "stateFingerprint": state_fingerprint,
            "stateSemanticSummary": state_semantic_summary,
            "cacheAccuracy": {
                "trustLevel": "fresh",
                "cacheTrustPenalty": 0.0,
                "mustRevalidate": False,
                "semanticDrift": {"level": "none", "reasons": []},
            },
            "scenarioKey": scenario_key,
            "agentRole": role,
            "description": config["description"],
            "source": "role_specific_mongo_cache",
            "retrievalMethod": "role_context_cache",
            "refreshMethod": role_method or retrieval_method,
            "freshnessPolicy": {
                "ttlSeconds": ttl_seconds,
                "usableStaleSeconds": usable_stale_seconds,
                "refreshTriggers": [
                    "park_state_sync",
                    "outcome_event",
                    "autodream_run",
                    "promotion_review",
                    "benchmark_result",
                ],
                "rollbackWatchBlocksLiveUse": role != "autodream_agent",
                "staleWhileRevalidate": True,
            },
            "priorityCollections": config["priorityCollections"],
            "decisionNeeds": config["decisionNeeds"],
            "retrieved": {
                "playbooks": playbooks,
                "incidents": incidents,
                "learnings": learnings,
            },
            "scenarioMemory": {
                "id": scenario_document["_id"],
                "rollbackState": scenario_document.get("rollbackState"),
                "groundTruth": scenario_document.get("groundTruth"),
            },
            "rollup": {
                "measuredPromotions": rollup_document.get("measuredPromotions"),
                "avgBenchmarkTakeRateLift": rollup_document.get("avgBenchmarkTakeRateLift"),
                "avgBenchmarkWinRate": rollup_document.get("avgBenchmarkWinRate"),
                "rollbackState": rollup_document.get("rollbackState"),
            },
            "roleSpecific": role_specific,
            "livePolicy": "candidate_autodream_rules_are_read_only_until_operator_promotion",
        }

    def _refresh_operational_intelligence(self, scenario_key: str | None = None, query: str | None = None) -> dict[str, Any]:
        now = _utc_now()
        live_state = self.latest_park_state() or {}
        scenario_key = scenario_key or _scenario_key_from_state(live_state) or _scenario_key_from_text(query or "")
        if not scenario_key or scenario_key == "unknown":
            scenario_key = _scenario_key_from_text(query or "", "ride_down")

        search_text = " ".join(part for part in [query or "", scenario_key, json.dumps(live_state.get("alerts", [])[:3])] if part)
        playbooks, playbook_method = self._retrieve_playbooks(search_text, 3)
        incidents = self._retrieve_incidents(search_text, 3)
        learnings = self._retrieve_learnings(search_text, 5)
        scenario_learnings = [
            row for row in learnings if row.get("scenarioKey") in {scenario_key, None, ""}
        ] or self._scenario_documents("agent_learnings", scenario_key, 5)
        dream_learnings = self._scenario_documents("dream_learnings", scenario_key, 5)
        benchmarks = self._scenario_documents("autodream_benchmarks", scenario_key, 10)
        latest_benchmark = benchmarks[0] if benchmarks else None
        ground_truth = self.ground_truth_improvement(100)
        scenario_ground_truth = None
        for item in ground_truth.get("scenario_breakdown", []) if isinstance(ground_truth, dict) else []:
            if item.get("scenario_key") == scenario_key:
                scenario_ground_truth = item
                break

        measured_counts = (
            scenario_ground_truth.get("counts", {}) if isinstance(scenario_ground_truth, dict) else {"improved": 0, "neutral": 0, "regressed": 0}
        )
        measured_promotions = int((scenario_ground_truth or {}).get("measured_promotions", 0) or 0)
        benchmark_lifts = [
            _number((row.get("summary", {}) if isinstance(row.get("summary"), dict) else {}).get("take_rate_lift"))
            for row in benchmarks
        ]
        benchmark_win_rates = [
            _number((row.get("summary", {}) if isinstance(row.get("summary"), dict) else {}).get("win_rate"))
            for row in benchmarks
        ]
        avg_take_lift = round(sum(benchmark_lifts) / len(benchmark_lifts), 3) if benchmark_lifts else 0.0
        avg_win_rate = round(sum(benchmark_win_rates) / len(benchmark_win_rates), 3) if benchmark_win_rates else 0.0
        rollback_state = "rollback_watch" if measured_counts.get("regressed", 0) > measured_counts.get("improved", 0) else "active"
        if latest_benchmark and latest_benchmark.get("confidence") == "regression_risk":
            rollback_state = "rollback_watch"

        scenario_document = {
            "_id": f"scenario_memory_{scenario_key}",
            "documentType": "scenario_memory_index",
            "createdAt": now,
            "updatedAt": now,
            "scenarioKey": scenario_key,
            "activeRules": scenario_learnings[:5],
            "dreamReviewQueue": dream_learnings[:5],
            "latestBenchmark": latest_benchmark,
            "groundTruth": scenario_ground_truth or {
                "status": "not_measured",
                "measured_promotions": 0,
                "counts": measured_counts,
                "confidence": "no_signal",
            },
            "rollbackState": rollback_state,
            "sourceCollections": ["agent_learnings", "dream_learnings", "autodream_benchmarks", "outcome_events"],
        }
        rollup_document = {
            "_id": f"ops_rollup_{scenario_key}",
            "documentType": "ops_metrics_rollup",
            "createdAt": now,
            "updatedAt": now,
            "scenarioKey": scenario_key,
            "measuredPromotions": measured_promotions,
            "counts": measured_counts,
            "benchmarkCount": len(benchmarks),
            "latestBenchmarkConfidence": (latest_benchmark or {}).get("confidence"),
            "avgBenchmarkTakeRateLift": avg_take_lift,
            "avgBenchmarkWinRate": avg_win_rate,
            "groundTruthConfidence": (scenario_ground_truth or ground_truth or {}).get("confidence", "no_signal"),
            "rollbackState": rollback_state,
        }
        cache_document = {
            "_id": f"agent_context_{scenario_key}",
            "documentType": "agent_context_cache",
            "createdAt": now,
            "updatedAt": now,
            "scenarioKey": scenario_key,
            "retrievalMethod": playbook_method,
            "source": "precomputed_mongo_cache",
            "retrieved": {
                "playbooks": playbooks,
                "incidents": incidents,
                "learnings": scenario_learnings[:5],
            },
            "rollup": {
                "measuredPromotions": measured_promotions,
                "avgBenchmarkTakeRateLift": avg_take_lift,
                "avgBenchmarkWinRate": avg_win_rate,
                "rollbackState": rollback_state,
            },
        }
        role_documents = [
            self._role_context_document(
                role,
                scenario_key,
                search_text,
                scenario_document,
                rollup_document,
                playbooks,
                incidents,
                scenario_learnings,
                dream_learnings,
                latest_benchmark,
                now,
                playbook_method,
            )
            for role in AGENT_ROLE_CONFIGS
        ]
        self._replace_memory_document("scenario_memory_index", scenario_document, 25)
        self._replace_memory_document("ops_metrics_rollups", rollup_document, 25)
        self._replace_memory_document("agent_context_cache", cache_document, 25)
        for document in role_documents:
            self._replace_memory_document("role_context_cache", document, 50)
        self._record_cache_event(
            "operational_intelligence_refresh",
            scenario_key,
            "react_agent",
            {
                "roleCaches": [document["agentRole"] for document in role_documents],
                "benchmarkCount": len(benchmarks),
                "rollbackState": rollback_state,
            },
        )
        self._refresh_agent_performance_scorecards(scenario_key, list(AGENT_ROLE_CONFIGS.keys()))
        return {
            "scenario_memory": _public_doc(scenario_document),
            "ops_rollup": _public_doc(rollup_document),
            "agent_context_cache": _public_doc(cache_document),
            "role_context_caches": [_public_doc(document) for document in role_documents],
        }

    def operational_intelligence(
        self,
        query: str = "",
        scenario_key: str | None = None,
        agent_role: str | None = None,
    ) -> dict[str, Any]:
        live_state = self.latest_park_state() or {}
        resolved_key = scenario_key or _scenario_key_from_state(live_state)
        if not resolved_key or resolved_key == "unknown":
            resolved_key = _scenario_key_from_text(query, "ride_down")
        resolved_role = _normalize_agent_role(agent_role, query)
        scenario_rows = self._scenario_documents("scenario_memory_index", resolved_key, 1)
        rollup_rows = self._scenario_documents("ops_metrics_rollups", resolved_key, 1)
        cache_rows = self._scenario_documents("agent_context_cache", resolved_key, 1)
        role_cache = self._latest_role_context_cache(resolved_key, resolved_role)
        if not scenario_rows or not rollup_rows or not cache_rows or not role_cache:
            refreshed = self._refresh_operational_intelligence(resolved_key, query)
            scenario_rows = [refreshed["scenario_memory"]]
            rollup_rows = [refreshed["ops_rollup"]]
            cache_rows = [refreshed["agent_context_cache"]]
            role_cache = next(
                (
                    document
                    for document in refreshed.get("role_context_caches", [])
                    if document.get("agentRole") == resolved_role
                ),
                None,
            )
        return {
            "status": "ready",
            "scenario_key": resolved_key,
            "agent_role": resolved_role,
            "scenario_memory": scenario_rows[0],
            "ops_rollup": rollup_rows[0],
            "agent_context_cache": cache_rows[0],
            "role_context_cache": role_cache,
            "available_role_caches": self._scenario_documents("role_context_cache", resolved_key, 10),
            "agent_performance_scorecards": self.agent_performance_scorecards(resolved_key),
        }

    def _collection_rows(
        self,
        collection_name: str,
        limit: int = 100,
        *,
        projection: dict[str, int] | None = None,
    ) -> list[dict[str, Any]]:
        collection = self._collection(collection_name)
        safe_limit = max(1, min(500, int(limit or 100)))
        if collection is not None:
            rows = list(
                collection.find({}, projection or {"embedding": 0, "embeddingText": 0})
                .sort([("updatedAt", DESCENDING), ("createdAt", DESCENDING)])
                .limit(safe_limit)
            )
            return [_public_doc(row) for row in rows]
        rows = sorted(
            deepcopy(self._fallback.get(collection_name, [])),
            key=lambda row: (row.get("updatedAt", ""), row.get("createdAt", "")),
            reverse=True,
        )[:safe_limit]
        return [_public_doc(row) for row in rows]

    def _scorecard_for_role(self, role: str, scenario_key: str | None = None, limit: int = 200) -> dict[str, Any]:
        now = _utc_now()
        role = _normalize_agent_role(role)
        events = [
            row
            for row in self._collection_rows("cache_events", limit)
            if row.get("agentRole") == role and (not scenario_key or row.get("scenarioKey") == scenario_key)
        ]
        attempt_event_types = {
            "role_cache_bypassed",
            "role_cache_read",
            "role_cache_stale_usable",
            "role_cache_miss",
            "role_cache_stale",
            "role_cache_rollback_blocked",
            "role_cache_dangerous_drift_blocked",
        }
        cache_events = [row for row in events if row.get("eventType") in attempt_event_types]
        reads = [row for row in cache_events if row.get("eventType") == "role_cache_read"]
        bypasses = [row for row in cache_events if row.get("eventType") == "role_cache_bypassed"]
        stale_usable = [row for row in cache_events if row.get("eventType") == "role_cache_stale_usable"]
        misses = [row for row in cache_events if row.get("eventType") == "role_cache_miss"]
        stale = [row for row in cache_events if row.get("eventType") == "role_cache_stale"]
        rollback_blocked = [row for row in cache_events if row.get("eventType") == "role_cache_rollback_blocked"]
        replay_metrics = self._cache_replay_metrics(role, scenario_key, limit)
        retrieval_latencies = [
            _number((row.get("details", {}) if isinstance(row.get("details"), dict) else {}).get("latencyMs"))
            for row in cache_events
            if isinstance(row.get("details"), dict) and (row.get("details", {}) or {}).get("latencyMs") is not None
        ]
        trust_penalties = [
            _number((row.get("details", {}) if isinstance(row.get("details"), dict) else {}).get("cacheTrustPenalty"))
            for row in cache_events
            if isinstance(row.get("details"), dict) and (row.get("details", {}) or {}).get("cacheTrustPenalty") is not None
        ]
        revalidation_events = [
            row
            for row in cache_events
            if isinstance(row.get("details"), dict) and bool((row.get("details", {}) or {}).get("mustRevalidate"))
        ]
        decisions = [
            row
            for row in self._collection_rows("agent_decisions", limit)
            if row.get("agentRole") == role and (not scenario_key or (row.get("stateScenario", {}) if isinstance(row.get("stateScenario"), dict) else {}).get("key") == scenario_key)
        ]
        decision_scores = [
            _number((row.get("arizeEvalSummary", {}) if isinstance(row.get("arizeEvalSummary"), dict) else {}).get("avgScore"))
            for row in decisions
        ]
        safety_scores = [
            _number((row.get("arizeEvalSummary", {}) if isinstance(row.get("arizeEvalSummary"), dict) else {}).get("safetyScore"))
            for row in decisions
        ]
        role_cache = self._latest_role_context_cache(scenario_key or _scenario_key_from_text("", "ride_down"), role) if scenario_key else None
        rollup = role_cache.get("rollup", {}) if isinstance((role_cache or {}).get("rollup"), dict) else {}
        total_cache_attempts = len(cache_events)
        cache_serves = len(reads) + len(stale_usable)
        hit_rate = round(cache_serves / total_cache_attempts, 3) if total_cache_attempts else 0.0
        stale_serve_rate = round(len(stale_usable) / total_cache_attempts, 3) if total_cache_attempts else 0.0
        avg_latency = round(sum(retrieval_latencies) / len(retrieval_latencies), 2) if retrieval_latencies else 0.0
        avg_trust_penalty = round(sum(trust_penalties) / len(trust_penalties), 3) if trust_penalties else 0.0
        avg_decision_score = round(sum(decision_scores) / len(decision_scores), 1) if decision_scores else 0.0
        safety_pass_rate = round(sum(1 for score in safety_scores if score >= 100) / len(safety_scores), 3) if safety_scores else 0.0
        gate_status = "serving_cache"
        if replay_metrics["failures"]:
            gate_status = "cache_replay_failed"
        elif rollback_blocked:
            gate_status = "rollback_blocked"
        elif stale:
            gate_status = "stale_fallback"
        elif stale_usable:
            gate_status = "stale_while_revalidate"
        elif total_cache_attempts and hit_rate < 0.5:
            gate_status = "warming"
        performance_status = (
            "watch"
            if replay_metrics["failures"]
            else "validated"
            if hit_rate >= 0.7 and avg_decision_score >= 75 and not rollback_blocked
            else "watch"
            if total_cache_attempts
            else "warming"
        )
        return {
            "_id": f"scorecard_{scenario_key or 'all'}_{role}",
            "documentType": "agent_performance_scorecard",
            "createdAt": now,
            "updatedAt": now,
            "scenarioKey": scenario_key or "all",
            "agentRole": role,
            "status": performance_status,
            "gateStatus": gate_status,
            "metrics": {
                "cacheReads": len(reads),
                "freshRetrievalBaselines": len(bypasses),
                "staleUsableServes": len(stale_usable),
                "cacheMisses": len(misses),
                "cacheStaleFallbacks": len(stale),
                "rollbackBlocks": len(rollback_blocked),
                "cacheHitRate": hit_rate,
                "staleServeRate": stale_serve_rate,
                "avgRetrievalLatencyMs": avg_latency,
                "avgCacheTrustPenalty": avg_trust_penalty,
                "mustRevalidateCount": len(revalidation_events),
                "decisionCount": len(decisions),
                "avgDecisionQuality": avg_decision_score,
                "safetyPassRate": safety_pass_rate,
                "benchmarkWinRate": _number(rollup.get("avgBenchmarkWinRate")),
                "benchmarkTakeRateLift": _number(rollup.get("avgBenchmarkTakeRateLift")),
                "measuredPromotions": int(_number(rollup.get("measuredPromotions"))),
                "cacheReplay": replay_metrics,
            },
            "recommendation": (
                "Cache replay failed; block AutoDream promotion and rerun with fresh state before trusting this role cache."
                if replay_metrics["failures"]
                else "Rollback watch is blocking live cache use; rerun benchmark or require operator review."
                if rollback_blocked
                else "Cache is serving stale-while-revalidate; accuracy is trust-penalized until refresh completes."
                if stale_usable
                else "Role cache is beyond usable window; refresh from current state before using cached decisions."
                if stale
                else "Cache is serving with usable performance evidence."
                if performance_status == "validated"
                else "Cache is warming; collect more role reads and decisions before claiming improvement."
            ),
        }

    def _cache_replay_metrics(self, role: str, scenario_key: str | None = None, limit: int = 50) -> dict[str, Any]:
        rows = [
            row
            for row in self._collection_rows("cache_accuracy_replays", limit)
            if row.get("agentRole") == role and (not scenario_key or row.get("scenarioKey") == scenario_key)
        ]
        if not rows:
            return {
                "replayCount": 0,
                "passRate": 0.0,
                "latestStatus": "not_run",
                "latestReplayId": None,
                "dangerousDriftBlockRate": 0.0,
                "staleUsableServeRate": 0.0,
                "actionStabilityRate": 0.0,
                "avgConfidenceDelta": 0.0,
                "failures": [],
            }
        passed = [row for row in rows if row.get("status") == "passed"]
        dangerous_total = dangerous_blocked = 0
        stale_total = stale_served = 0
        stable_total = stable_count = 0
        confidence_deltas: list[float] = []
        failures: list[str] = []
        for row in rows:
            summary = row.get("summary", {}) if isinstance(row.get("summary"), dict) else {}
            failures.extend(str(item) for item in summary.get("failures", []) if item)
            for result in row.get("results", []) if isinstance(row.get("results"), list) else []:
                if not isinstance(result, dict):
                    continue
                mode = result.get("mode")
                if mode == "dangerous_drift_blocked":
                    dangerous_total += 1
                    if (result.get("policyGate", {}) if isinstance(result.get("policyGate"), dict) else {}).get("status") == "blocked":
                        dangerous_blocked += 1
                if mode == "stale_usable_cache":
                    stale_total += 1
                    if result.get("retrievalMethod") == "role_context_cache_stale_usable":
                        stale_served += 1
                if "selectedActionStableVsFresh" in result:
                    stable_total += 1
                    if result.get("selectedActionStableVsFresh"):
                        stable_count += 1
                confidence = result.get("confidence", {}) if isinstance(result.get("confidence"), dict) else {}
                if confidence.get("delta") is not None:
                    confidence_deltas.append(_number(confidence.get("delta")))
        latest = rows[0]
        return {
            "replayCount": len(rows),
            "passRate": round(len(passed) / len(rows), 3),
            "latestStatus": latest.get("status", "unknown"),
            "latestReplayId": latest.get("_id"),
            "dangerousDriftBlockRate": round(dangerous_blocked / dangerous_total, 3) if dangerous_total else 0.0,
            "staleUsableServeRate": round(stale_served / stale_total, 3) if stale_total else 0.0,
            "actionStabilityRate": round(stable_count / stable_total, 3) if stable_total else 0.0,
            "avgConfidenceDelta": round(sum(confidence_deltas) / len(confidence_deltas), 1) if confidence_deltas else 0.0,
            "failures": sorted(set(failures)),
        }

