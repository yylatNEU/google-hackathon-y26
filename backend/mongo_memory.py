def _utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")


def _utc_after(seconds: int | float) -> str:
    return (datetime.now(UTC) + timedelta(seconds=max(0, float(seconds or 0)))).isoformat(timespec="seconds").replace("+00:00", "Z")


def _parse_utc(value: Any) -> datetime | None:
    if isinstance(value, datetime):
        return value.astimezone(UTC)
    if not isinstance(value, str) or not value:
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(UTC)
    except ValueError:
        return None


def _clean_for_bson(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _clean_for_bson(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_clean_for_bson(item) for item in value]
    if isinstance(value, tuple):
        return [_clean_for_bson(item) for item in value]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


